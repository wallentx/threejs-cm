const NAME_TO_ID = Object.freeze({
  'MAS-36 Rifle': 'MAS36',
  'FM 24/29 LMG': 'FM2429',
  'MAS-38 SMG': 'MAS38',
  Kar98k: 'KAR98K',
  'MG34 LMG': 'MG34',
  MP40: 'MP40'
});

export function weaponIdFromName(name) {
  return NAME_TO_ID[name] ?? name ?? null;
}

export function getWeapon(idOrName) {
  return WEAPONS[weaponIdFromName(idOrName)] ?? null;
}
