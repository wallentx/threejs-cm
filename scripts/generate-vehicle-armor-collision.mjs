import { chmod, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { compileVehicleArmorMesh } from '../src/calibration/VehicleArmorMeshCompiler.js';
import {
  FRANCE_1940_VEHICLE_ARMOR_SOURCES
} from '../src/content/france1940/render/VehicleArmorSourceManifest.js';
import {
  FRANCE_1940_VEHICLE_MESH_FACTORIES
} from '../src/content/france1940/render/vehicleMeshFactories.js';

const outputPath = resolve(
  'src/content/france1940/vehicleData/GeneratedVehicleArmorCollision.js'
);
const records = {};

function encodeFloat32(values) {
  const typed = new Float32Array(values);
  return Buffer.from(typed.buffer, typed.byteOffset, typed.byteLength).toString('base64');
}

function encodeUint16(values, vertexCount) {
  if (vertexCount > 0xffff) {
    throw new Error(`Armor source has ${vertexCount} vertices; Uint16 index packing overflow`);
  }
  const typed = new Uint16Array(values);
  return Buffer.from(typed.buffer, typed.byteOffset, typed.byteLength).toString('base64');
}

function packRecord(record) {
  return {
    ...record,
    volumes: record.volumes.map(volume => ({
      ...volume,
      vertices: undefined,
      vertexCount: volume.vertices.length / volume.vertexStride,
      vertexData: encodeFloat32(volume.vertices),
      plates: volume.plates.map(plate => ({
        ...plate,
        triangles: undefined,
        triangleCount: plate.triangles.length / plate.triangleStride,
        triangleData: encodeUint16(
          plate.triangles,
          volume.vertices.length / volume.vertexStride
        )
      }))
    }))
  };
}

for (const [modelId, manifest] of Object.entries(FRANCE_1940_VEHICLE_ARMOR_SOURCES)) {
  const factory = FRANCE_1940_VEHICLE_MESH_FACTORIES[modelId];
  if (!factory) throw new Error(`No vehicle mesh factory for ${modelId}`);
  records[modelId] = packRecord(compileVehicleArmorMesh(factory(), manifest));
}

const serialized = JSON.stringify(records);
const source = `// Generated by scripts/generate-vehicle-armor-collision.mjs. Do not edit.\n`
  + `const PACKED_RECORDS = ${serialized};\n\n`
  + `function bytes(encoded) {\n`
  + `  return Uint8Array.from(atob(encoded), value => value.charCodeAt(0));\n`
  + `}\n\n`
  + `function float32Values(encoded, count) {\n`
  + `  const data = bytes(encoded);\n`
  + `  const view = new DataView(data.buffer, data.byteOffset, data.byteLength);\n`
  + `  return Array.from({ length: count * 3 }, (_, index) => (\n`
  + `    view.getFloat32(index * 4, true)\n`
  + `  ));\n`
  + `}\n\n`
  + `function uint16Values(encoded, count) {\n`
  + `  const data = bytes(encoded);\n`
  + `  const view = new DataView(data.buffer, data.byteOffset, data.byteLength);\n`
  + `  return Array.from({ length: count * 3 }, (_, index) => (\n`
  + `    view.getUint16(index * 2, true)\n`
  + `  ));\n`
  + `}\n\n`
  + `function unpack(record) {\n`
  + `  return { ...record, volumes: record.volumes.map(volume => {\n`
  + `    const { vertexData, vertexCount, ...metadata } = volume;\n`
  + `    return { ...metadata, vertices: float32Values(vertexData, vertexCount),\n`
  + `      plates: volume.plates.map(plate => {\n`
  + `        const { triangleData, triangleCount, ...plateMetadata } = plate;\n`
  + `        return { ...plateMetadata, triangles: uint16Values(triangleData, triangleCount) };\n`
  + `      })\n`
  + `    };\n`
  + `  }) };\n`
  + `}\n\n`
  + `export const GENERATED_VEHICLE_ARMOR_COLLISIONS = Object.freeze(\n`
  + `  Object.fromEntries(Object.entries(PACKED_RECORDS).map(([id, record]) => [id, unpack(record)]))\n`
  + `);\n\n`
  + `export function getGeneratedVehicleArmorCollision(modelId) {\n`
  + `  return GENERATED_VEHICLE_ARMOR_COLLISIONS[modelId] ?? null;\n`
  + `}\n`;

await writeFile(outputPath, source);
await chmod(outputPath, 0o644);
console.log(`Wrote ${Object.keys(records).length} vehicle armor records to ${outputPath}`);
